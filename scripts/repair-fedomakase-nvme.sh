#!/bin/bash
# repair-fedomakase-nvme.sh
# Complete live NVMe repair & full Omarchy Quattro payload sync for the Acer Googlebook 14 (Moonstone).
# Can be executed remotely from the Mac host over SSH (`./scripts/repair-fedomakase-nvme.sh 192.168.8.219`)
# once the Googlebook boots into Fedomakase Linux (or the initramfs recovery shell).

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
TARGET_IP="${1:-192.168.8.219}"
OMARCHY_SRC="${2:-/Volumes/LRMS4/Projects/moonstone-googlebook/iso-extracted/omarchy-fedora}"
SSH_OPTS=(-o StrictHostKeyChecking=no -o ConnectTimeout=5)

echo "==> 1. Checking SSH connectivity to Googlebook at root@${TARGET_IP}..."
ssh "${SSH_OPTS[@]}" "root@${TARGET_IP}" "uname -a; df -h / /home /boot 2>/dev/null || true"

echo "==> 2. Streaming complete 220 MB Omarchy Quattro tree (all themes, wallpapers, Lua configs, SDDM, UWSM) to NVMe..."
tar -C "$OMARCHY_SRC" --no-xattrs -cf - . | \
  ssh "${SSH_OPTS[@]}" "root@${TARGET_IP}" "mkdir -p /usr/share/omarchy && tar -C /usr/share/omarchy -xf -"

echo "==> 3. Installing googlebook-sysroot-sync, googlebook-switch-slot, and /boot/googlebook-theme/theme.conf..."
scp "${SSH_OPTS[@]}" \
  "$SCRIPT_DIR/bin/googlebook-sysroot-sync" \
  "$SCRIPT_DIR/bin/googlebook-switch-slot" \
  "$SCRIPT_DIR/bin/fedomakase-googlebook-slotb" \
  "root@${TARGET_IP}:/usr/local/bin/"

ssh "${SSH_OPTS[@]}" "root@${TARGET_IP}" "mkdir -p /boot/googlebook-theme"
scp "${SSH_OPTS[@]}" \
  "$SCRIPT_DIR/googleboot-menu/theme/theme.conf" \
  "root@${TARGET_IP}:/boot/googlebook-theme/theme.conf"

echo "==> 4. Running full Omarchy + SDDM + Hyprland + UWSM repair on NVMe..."
ssh "${SSH_OPTS[@]}" "root@${TARGET_IP}" '
set -e
chmod 755 /usr/local/bin/googlebook-sysroot-sync /usr/local/bin/googlebook-switch-slot /usr/local/bin/fedomakase-googlebook-slotb
ln -sf /usr/local/bin/googlebook-switch-slot /usr/local/bin/boot-android

# Copy system /etc defaults from /usr/share/omarchy/etc
cp -rn /usr/share/omarchy/etc/* /etc/ 2>/dev/null || true
cp -rf /usr/share/omarchy/etc/sddm.conf.d /etc/ 2>/dev/null || true

# Run googlebook-sysroot-sync against live / (creating /sysroot -> / symlink temporarily if not in initrd)
if [ ! -e /sysroot ]; then
  ln -s / /sysroot
  CLEAN_SYSROOT=1
fi
/usr/local/bin/googlebook-sysroot-sync
if [ "${CLEAN_SYSROOT:-0}" = "1" ]; then
  rm -f /sysroot
fi

# Verify critical files exist and have no autogenerated stub
PRIMARY_USER=$(awk -F: "\$3 >= 1000 && \$3 < 60000 && \$1 != \"nobody\" && \$1 != \"nfsnobody\" {print \$1; exit}" /etc/passwd)
[ -z "$PRIMARY_USER" ] && PRIMARY_USER="jcasco"
echo "Verified user: $PRIMARY_USER"
ls -la "/home/$PRIMARY_USER/.config/hypr/hyprland.lua" "/usr/share/sddm/hyprland.lua" "/usr/share/uwsm/env.d/10-omarchy"
grep -n "bootstrap.lua" "/home/$PRIMARY_USER/.config/hypr/hyprland.lua"

systemctl daemon-reload
systemctl restart googlebook-gpu-init.service sddm.service
'
echo "==> Done! Fedomakase NVMe installation is fully repaired and active."
